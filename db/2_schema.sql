-- выполнить под postgres в базе tournament_db

CREATE TABLE users (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100) NOT NULL CHECK (trim(name) <> ''),
    email VARCHAR(100) UNIQUE
);

CREATE TABLE teams (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL CHECK (trim(name) <> ''),
    captain_id BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE team_members (
    team_id BIGINT NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (team_id, user_id)
);

CREATE TABLE tournaments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL CHECK (trim(name) <> ''),
    team_limit  INTEGER      NOT NULL CHECK (team_limit >= 2),
    status      VARCHAR(20)  NOT NULL CHECK (status IN ('REGISTRATION', 'IN_PROGRESS', 'FINISHED')),
    winner_id   BIGINT REFERENCES teams (id) ON DELETE SET NULL,
    finished_at TIMESTAMP,
    CHECK (status <> 'FINISHED' OR finished_at IS NOT NULL)
);

CREATE TABLE team_applications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id       BIGINT      NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    tournament_id BIGINT      NOT NULL REFERENCES tournaments (id) ON DELETE CASCADE,
    status        VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'WITHDRAWN')),
    applied_at    TIMESTAMP   NOT NULL,
    UNIQUE (team_id, tournament_id)
);

CREATE TABLE matches (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT      NOT NULL REFERENCES tournaments (id) ON DELETE CASCADE,
    team1_id      BIGINT      NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    team2_id      BIGINT      NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    score1        INTEGER     NOT NULL DEFAULT 0 CHECK (score1 >= 0),
    score2        INTEGER     NOT NULL DEFAULT 0 CHECK (score2 >= 0),
    status        VARCHAR(20) NOT NULL CHECK (status IN ('SCHEDULED', 'FINISHED')),
    played_at     TIMESTAMP,
    CHECK (team1_id <> team2_id),
    CHECK (status <> 'FINISHED' OR played_at IS NOT NULL)
);

GRANT CONNECT ON DATABASE tournament_db TO tournament_app;
GRANT USAGE ON SCHEMA public TO tournament_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO tournament_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO tournament_app;
